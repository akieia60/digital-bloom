/**
 * Get all messages for a given category + tone.
 * Returns an array of message strings (or empty array if not found).
 */
export function getMessages(category, tone) {
  const cat = bloomMessages[category];
  if (!cat) return [];
  return cat[tone] || [];
}

/**
 * Get a random message for a given category + tone.
 */
export function getRandomMessage(category, tone) {
  const messages = getMessages(category, tone);
  if (!messages.length) return '';
  return messages[Math.floor(Math.random() * messages.length)];
}

