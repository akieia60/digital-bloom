/**
 * Returns available tones for a given category
 * (some category+tone combos don't exist in the message bank)
 */
export function getAvailableTones(categoryId) {
  const cat = MESSAGE_BANK[categoryId];
  if (!cat) return BLOOM_TONES;
  const availableIds = new Set(Object.keys(cat));
  return BLOOM_TONES.filter((t) => availableIds.has(t.id));
}
