/**
 * Get messages for a specific category and tone.
 * Falls back to heartfelt if the tone is not defined for the category.
 */
export function getMessages(category, tone) {
  const cat = MESSAGE_BANK[category];
  if (!cat) return [];
  return cat[tone] || cat['heartfelt'] || [];
}

